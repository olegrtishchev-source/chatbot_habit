"""Точка входа фонового сервиса оповещений.

Логика оповещений и переноса привычек появится на этапе 6 плана.
"""

import time


def main() -> None:
    """Заготовка сервиса — пока просто удерживает контейнер живым."""
    while True:
        time.sleep(3600)


if __name__ == "__main__":
    main()
